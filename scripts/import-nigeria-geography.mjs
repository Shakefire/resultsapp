#!/usr/bin/env node
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';

const expected = { states: 37, lgas: 774, wards: 8809 };
const sourceVersion = 'OpenAdminData-2026-06-01';
const stateCodes = new Map([
  ['Abia', 'AB'], ['Adamawa', 'AD'], ['Akwa Ibom', 'AK'], ['Anambra', 'AN'],
  ['Bauchi', 'BA'], ['Bayelsa', 'BY'], ['Benue', 'BE'], ['Borno', 'BO'],
  ['Cross River', 'CR'], ['Delta', 'DE'], ['Ebonyi', 'EB'], ['Edo', 'ED'],
  ['Ekiti', 'EK'], ['Enugu', 'EN'], ['Gombe', 'GO'], ['Imo', 'IM'],
  ['Jigawa', 'JI'], ['Kaduna', 'KD'], ['Kano', 'KN'], ['Katsina', 'KT'],
  ['Kebbi', 'KE'], ['Kogi', 'KO'], ['Kwara', 'KW'], ['Lagos', 'LA'],
  ['Nasarawa', 'NA'], ['Niger', 'NI'], ['Ogun', 'OG'], ['Ondo', 'ON'],
  ['Osun', 'OS'], ['Oyo', 'OY'], ['Plateau', 'PL'], ['Rivers', 'RI'],
  ['Sokoto', 'SO'], ['Taraba', 'TA'], ['Yobe', 'YO'], ['Zamfara', 'ZA'],
  ['Federal Capital Territory', 'FC'],
]);

function sql(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}

function insertRows(table, columns, rows, conflictColumns, updates) {
  if (rows.length === 0) return '';
  const lines = rows.map((row) => `  (${row.map(sql).join(', ')})`).join(',\n');
  return `insert into public.${table} (${columns.join(', ')}) values\n${lines}\non conflict (${conflictColumns.join(', ')}) do update set\n  ${updates.map((column) => `${column} = excluded.${column}`).join(',\n  ')};\n`;
}

function validate(data) {
  if (!Array.isArray(data) || data.length !== expected.states) {
    throw new Error(`Expected ${expected.states} state/FCT records; received ${data?.length ?? 'invalid input'}.`);
  }
  let lgaCount = 0;
  let wardCount = 0;
  const stateIds = new Set();
  const lgaIds = new Set();
  const wardIds = new Set();
  for (const state of data) {
    const name = state?.name?.en;
    if (!state?.id || !stateCodes.has(name) || stateIds.has(state.id) || !Array.isArray(state.lga)) {
      throw new Error(`Invalid, duplicate, or unrecognized state record: ${name ?? 'unnamed'}.`);
    }
    stateIds.add(state.id);
    for (const lga of state.lga) {
      if (!lga?.id || !lga?.name?.en || lgaIds.has(lga.id) || !Array.isArray(lga.ward)) {
        throw new Error(`Invalid or duplicate LGA record beneath ${name}.`);
      }
      lgaIds.add(lga.id);
      lgaCount += 1;
      for (const ward of lga.ward) {
        if (!ward?.id || !ward?.name?.en || wardIds.has(ward.id)) {
          throw new Error(`Invalid or duplicate ward record beneath ${lga.name.en}.`);
        }
        wardIds.add(ward.id);
        wardCount += 1;
      }
    }
  }
  if (lgaCount !== expected.lgas) {
    throw new Error(`Expected ${expected.lgas} LGA/Area Council records; received ${lgaCount}.`);
  }
  return { states: data.length, lgas: lgaCount, wards: wardCount };
}

const inputPath = resolve(process.argv[2] ?? 'data/geography/nigeria-open-admin-data-hierarchy.json');
const outputPath = resolve(process.argv[3] ?? 'supabase/seed/nigeria-geography.sql');
const allowWardMismatch = process.argv.includes('--allow-ward-count-mismatch');
const parsed = JSON.parse(await readFile(inputPath, 'utf8'));
const data = Array.isArray(parsed) ? parsed : parsed?.data;
const counts = validate(data);
console.log(`Geography source counts: ${counts.states} states/FCT, ${counts.lgas} LGAs/Area Councils, ${counts.wards} wards.`);
if (counts.wards !== expected.wards && !allowWardMismatch) {
  throw new Error(
    `Ward count differs from INEC's published ${expected.wards} (2023) total. Reconcile the source, or explicitly pass --allow-ward-count-mismatch to generate a provisional seed.`,
  );
}
const seedVersion = counts.wards === expected.wards ? sourceVersion : `${sourceVersion}-PROVISIONAL`;

const lgas = [];
const wards = [];
for (const state of data) {
  const stateCode = stateCodes.get(state.name.en);
  for (const [lgaIndex, lga] of state.lga.entries()) {
    const lgaCode = String(lgaIndex + 1).padStart(2, '0');
    lgas.push([lgaCode, lga.id, stateCode, lga.name.en, stateCode === 'FC', seedVersion]);
    for (const [wardIndex, ward] of lga.ward.entries()) {
      const wardCode = String(wardIndex + 1).padStart(2, '0');
      wards.push([wardCode, ward.id, stateCode, lgaCode, ward.name.en, seedVersion]);
    }
  }
}

const generated = [
  '-- Generated by scripts/import-nigeria-geography.mjs. Do not hand-edit.',
  '-- Source: Open Admin Data Nigeria Administrative Divisions, CC-BY-4.0.',
  '-- https://github.com/open-admin-data/nigeria-administrative-divisions',
  `-- Source version: ${seedVersion}; counts: ${counts.states}/${counts.lgas}/${counts.wards}.`,
  ...(seedVersion.endsWith('-PROVISIONAL') ? ['-- PROVISIONAL: ward count mismatch; reconcile with INEC before applying to production.'] : []),
  'begin;',
  insertRows('lgas', ['code', 'source_code', 'state_code', 'name', 'is_fct_area_council', 'source_version'], lgas,
    ['state_code', 'code'], ['source_code', 'name', 'is_fct_area_council', 'source_version']),
  insertRows('wards', ['code', 'source_code', 'state_code', 'lga_code', 'name', 'source_version'], wards,
    ['state_code', 'lga_code', 'code'], ['source_code', 'name', 'source_version']),
  'commit;',
].join('\n');

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, generated, 'utf8');
console.log(`Generated ${outputPath}`);
