// lib/core/constants/app_spacing.dart

/// Consistent spacing scale for Smart Electoral Results App.
class AppSpacing {
  AppSpacing._();

  static const double xs = 4.0;
  static const double sm = 8.0;
  static const double md = 12.0;
  static const double lg = 16.0;
  static const double xl = 20.0;
  static const double xxl = 24.0;
  static const double xxxl = 32.0;
  static const double huge = 40.0;

  /// Horizontal padding for small screens (360–375px)
  static const double horizontalPaddingSmall = 20.0;

  /// Horizontal padding for larger screens (390px+)
  static const double horizontalPaddingLarge = 24.0;

  /// Standard vertical gap between form fields
  static const double fieldGap = 16.0;

  /// Standard vertical gap between form sections
  static const double sectionGap = 24.0;

  /// Minimum touch target height (accessibility)
  static const double minTouchTarget = 44.0;

  /// Standard input field height
  static const double inputHeight = 52.0;

  /// Primary button height
  static const double buttonHeight = 52.0;
}
